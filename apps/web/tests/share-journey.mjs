import assert from "node:assert/strict";
import {mkdir,mkdtemp,rm,writeFile} from "node:fs/promises";
import path from "node:path";
import {tmpdir} from "node:os";
import {randomBytes} from "node:crypto";
import {chromium} from "playwright-core";
import {previewBoundary} from "./preview-boundary.mjs";
import {createServer,parseGatewayConfig} from "../../server/dist/app.js";
import {installationCode} from "../../server/dist/routes/auth.js";
import {SecretMasker} from "../../server/dist/security/secret-masker.js";
import {openDatabase} from "../../server/dist/db/index.js";
import {readSecurityConfig} from "../../server/dist/security/config.js";
import {WorkspaceFiles} from "../../server/dist/files/workspace-files.js";

process.env.NODE_ENV="production";
const root=await mkdtemp(path.join(tmpdir(),"deck-share-e2e-")),data=path.join(root,"data");
let server,db,browser;
const errors=[];
function observe(page){page.on("console",msg=>{if(msg.type()==="error")errors.push(msg.text());});page.on("pageerror",e=>errors.push(e.message));}
try{
  await mkdir(data);
  db=await openDatabase(data,root);
  const ctx={...db,masterKey:randomBytes(32),masker:new SecretMasker(),gatewayConfig:parseGatewayConfig()};
  server=createServer(ctx,{dataDirectory:data,workspaceRoot:root});
  const origin=await server.listen({host:"127.0.0.1",port:0});
  browser=await chromium.launch();
  const control=await browser.newContext({viewport:{width:1440,height:900}});
  const r=await control.request.post(origin+"/api/auth/setup",{data:{password:"ShareBrowserFixture123",setup_code:installationCode(db.native,ctx.masterKey)}});
  assert.equal(r.status(),200);
  db.native.prepare("INSERT INTO settings(key,value,updated_at) VALUES('onboarding_completed','1',?) ON CONFLICT(key) DO UPDATE SET value='1'").run(new Date().toISOString());
  const files=new WorkspaceFiles(ctx,data,()=>{});
  const workspace=await files.create("Share lab","conservative");
  await previewBoundary(control,origin,files,workspace);
  const name="成品验收.html";
  await writeFile(path.join(workspace.path,name),'<!doctype html><h1>验收文件</h1><button onclick="this.textContent=\'交互正常\'">检查交互</button>');
  const a=await files.registerArtifact(workspace.id,null,null,name,"added");
  const page=await control.newPage();observe(page);await page.goto(origin+"/artifacts");
  const shareButton=page.getByRole("button",{name:"公开分享 "+name,exact:true});
  await shareButton.click();
  const dialog=page.getByRole("dialog",{name:"公开分享"});
  await dialog.getByLabel("提取码",{exact:true}).fill("482016");
  await dialog.getByLabel("最多阅读次数").fill("1");
  await dialog.getByRole("button",{name:"生成分享链接"}).click();
  const text=dialog.getByLabel("分享链接与提取码");
  await text.waitFor();const url=(await text.inputValue()).split("\n")[0];assert.ok(url.startsWith(origin+"/s/"));
  const guest=await browser.newContext({viewport:{width:390,height:844}});
  const reader=await guest.newPage();observe(reader);
  const first=await reader.goto(url);
  assert.match(first.headers()["content-security-policy"],/default-src 'none'/);
  await reader.getByLabel("提取码",{exact:true}).fill("482016");
  await reader.getByRole("button",{name:"查看成品"}).click();
  const frame=reader.frameLocator("iframe");
  await frame.getByRole("button",{name:"检查交互"}).click({timeout:12000});
  await frame.getByRole("button",{name:"交互正常"}).waitFor();
  assert.equal(await reader.locator("iframe").getAttribute("sandbox"),"allow-scripts");
  assert.equal(await reader.getByRole("link",{name:/下载/}).count(),0);
  await reader.reload();await frame.getByRole("heading",{name:"验收文件"}).waitFor();
  assert.equal(db.native.prepare("SELECT view_count FROM public_shares WHERE artifact_id=?").pluck().get(a.id),1);
  await page.goto(origin+"/system");
  await page.getByRole("button",{name:"临时访问管理"}).click();
  await page.getByRole("button",{name:"公开分享",exact:true}).click();
  page.once("dialog",d=>d.accept());
  await page.getByRole("button",{name:"吊销分享"}).click();
  await page.getByText("已吊销",{exact:true}).waitFor();
  await reader.reload();await reader.getByRole("heading",{name:"分享已失效"}).waitFor();
  const mdName="diagram.md";
  await writeFile(path.join(workspace.path,mdName),"# Build diagram\n\n```mermaid\nflowchart LR\nA[Compile] --> B[Ship]\n```\n");
  const md=await files.registerArtifact(workspace.id,null,null,mdName,"added");
  const link=await control.request.post(origin+"/api/shares",{data:{artifact_id:md.id}});
  assert.equal(link.status(),201);
  const cfg={...readSecurityConfig(db.native),public_enabled:true,entry_enabled:true,basic_enabled:true,ip_mode:"allow",ip_ranges:["203.0.113.10"]};
  db.native.prepare("UPDATE settings SET value=? WHERE key='security.config'").run(JSON.stringify(cfg));
  await reader.goto(origin+(await link.json()).url);
  await reader.getByRole("heading",{name:"Build diagram"}).waitFor();
  await reader.frameLocator('iframe[title="Mermaid 图表"]').locator("svg").waitFor({timeout:12000});
  assert.deepEqual(errors,[]);
  console.log("E4: admin share form, incognito mobile passcode, interactive sandbox, one-view refresh, UI revocation; 0 console errors, 0 page errors");
}finally{
  await browser?.close();await server?.close();db?.native.close();await rm(root,{recursive:true,force:true});
}
